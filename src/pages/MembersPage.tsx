const getTermColor = (term: string) => {
  const termNumber = Number(term);

  if (!Number.isInteger(termNumber) || termNumber < 1 || termNumber > 20) {
    return "#8c8c8c";
  }

  const progress = (termNumber - 1) / 19;
  const hue = 220 - progress * 185;
  return `hsl(${hue}, 70%, 58%)`;
};

